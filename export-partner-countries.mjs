/** @param {Record<string, Record<string, number>>} byNetwork */
function mergeCountryCounts(byNetwork) {
  /** @type {Map<string, Record<string, number>>} */
  const countries = new Map()

  for (const networkKey of NETWORK_KEYS) {
    const byCountry = byNetwork[networkKey] ?? {}
    for (const [code, count] of Object.entries(byCountry)) {
      const iso = normalizePartnerIso(code)
      if (!iso) continue
      if (!countries.has(iso)) {
        countries.set(iso, Object.fromEntries(NETWORK_KEYS.map((k) => [k, 0])))
      }
      countries.get(iso)[networkKey] += count
    }
  }

  return countries
}

function exportCountsFromDatabase() {
  /** @type {Record<string, Record<string, number>>} */
  const byNetwork = {}

  for (const networkKey of NETWORK_KEYS) {
    process.stderr.write(`  ${networkKey}… `)
    byNetwork[networkKey] = fetchPartnerCountsByCountryOrThrow(networkKey)
    const total = Object.values(byNetwork[networkKey]).reduce((a, b) => a + b, 0)
    if (total === 0 && LINE_NETWORK_KEYS.includes(networkKey)) {
      process.stderr.write(
        `0 (no partner rows for selected design lines on this DB — check cruise_line/cruise_program)\n`,
      )
    } else {
      process.stderr.write(`${total}\n`)
    }
  }

  return byNetwork
}

/** @param {string} filePath */
function readExistingMetadata(filePath) {
  /** @type {Record<string, { name?: string, countryCode?: string, description?: string }>} */
  const meta = { ...COUNTRY_META_OVERRIDES }

  if (!fs.existsSync(filePath)) return meta

  const content = fs.readFileSync(filePath, 'utf8')
  const entryRe =
    /name:\s*"([^"]+)"[\s\S]*?countryCode:\s*"([^"]+)"([\s\S]*?)?networks:/g

  let match
  while ((match = entryRe.exec(content)) !== null) {
    const [, name, countryCode, middle = ''] = match
    const descMatch = middle.match(/description:\s*"([^"]+)"/)
    meta[countryCode] = {
      name,
      countryCode,
      ...(descMatch ? { description: descMatch[1] } : {}),
    }
  }

  return meta
}

/** @param {Map<string, Record<string, number>>} countries @param {Record<string, { name?: string, countryCode?: string, description?: string }>} meta @param {number} contributingCountries */
function renderPartnerCountries(countries, meta, contributingCountries) {
  const generatedAt = new Date().toISOString().slice(0, 10)

  const sortedCodes = [...countries.keys()].sort((a, b) => {
    const nameA = meta[a]?.name ?? ISO_COUNTRY_NAMES[a] ?? a
    const nameB = meta[b]?.name ?? ISO_COUNTRY_NAMES[b] ?? b
    return nameA.localeCompare(nameB)
  })

  const entries = sortedCodes.map((code) => {
    const networks = countries.get(code)
    const info = meta[code] ?? {
      name: ISO_COUNTRY_NAMES[code] ?? code,
      countryCode: code,
    }

    const networkLiteral = NETWORK_KEYS.map((k) => `${k}: ${networks[k] ?? 0}`).join(', ')

    const lines = [
      '  {',
      `    name: ${JSON.stringify(info.name)},`,
      `    countryCode: ${JSON.stringify(info.countryCode ?? code)},`,
    ]

    if (info.description) {
      lines.push(`    description: ${JSON.stringify(info.description)},`)
    }

    lines.push(`    networks: { ${networkLiteral} }`, '  }')
    return lines.join('\n')
  })

  return `/**
 * Partner Countries Data
 *
 * AUTO-GENERATED by oceanops-data-exports/export-partner-countries.mjs — do not edit counts by hand.
 * Regenerate: npm run export:partners (from oceanops-data-exports or oceanops-report-card)
 *
 * Data source: OceanOPS PostgreSQL (ptf_loc_n + cruise_program for lines), filters in sql/*.sql
 * Last updated: ${generatedAt}
 *
 * Note: goShip can be:
 * - A number (0 or positive): GO-SHIP edition cruise count for the country (lead program country)
 * - -1: represents "X" (participates but count not tracked)
 */

interface CountryNetworks {
  driftingBuoys: number
  argo: number
  oceanGliders: number
  aniBOS: number
  fvon: number
  sotVos: number
  sotAsap: number
  sot: number
  goShip: number // -1 represents "X" (participates but not counted)
  gloss: number
  oceanSites: number
  mooredBuoys: number
  tsunamiBuoys: number
  hfRadars: number
}

export interface PartnerCountry {
  name: string
  countryCode?: string // ISO 3166-1 alpha-2 code for flag display
  description?: string // Optional description specific to this country
  networks: CountryNetworks
}

export const partnerCountries: PartnerCountry[] = [
${entries.join(',\n')}
]

/** Globe/report filter countries (rollup + whitelist). Matches simple-map getFilterableCountryNames. */
export const CONTRIBUTING_COUNTRIES = ${contributingCountries}
`
}

/** @param {Map<string, Record<string, number>>} countries @param {Record<string, { name?: string, countryCode?: string, description?: string }>} meta @param {number} contributingCountries */
function renderPartnerCountriesJson(countries, meta, contributingCountries) {
  const generatedAt = new Date().toISOString().slice(0, 10)

  const sortedCodes = [...countries.keys()].sort((a, b) => {
    const nameA = meta[a]?.name ?? ISO_COUNTRY_NAMES[a] ?? a
    const nameB = meta[b]?.name ?? ISO_COUNTRY_NAMES[b] ?? b
    return nameA.localeCompare(nameB)
  })

  const countryList = sortedCodes.map((code) => {
    const networks = countries.get(code)
    const info = meta[code] ?? {
      name: ISO_COUNTRY_NAMES[code] ?? code,
      countryCode: code,
    }

    return {
      name: info.name,
      countryCode: info.countryCode ?? code,
      ...(info.description ? { description: info.description } : {}),
      geoCountryNames: geoNamesForIso(code),
      networks: Object.fromEntries(
        NETWORK_KEYS.map((k) => [k, networks[k] ?? 0]),
      ),
    }
  })

  return {
    generatedAt,
    edition: EXPORT_EDITION_LABEL,
    source: 'OceanOPS PostgreSQL partner export (sql/*.sql criteria)',
    contributingCountries,
    countries: countryList,
    byGeoCountryName: buildGeoCountryIndex(countries, meta),
  }
}

const __filename = fileURLToPath(import.meta.url)

/** @param {string[]} argv */
function parsePartnerArgs(argv) {
  const exportPaths = resolveExportPaths(argv)
  return {
    exportPaths,
    output: exportPaths.PARTNER_COUNTRIES_TS,
    outputJson: exportPaths.PARTNER_COUNTRIES_JSON,
    dryRun: argv.includes('--dry-run'),
    noSummary: argv.includes('--no-summary'),
  }
}

/** @param {string[]} [argv] @param {{ noSummary?: boolean }} [options] */
export async function runPartnerExport(argv = process.argv.slice(2), options = {}) {
  const { exportPaths, output: OUTPUT, outputJson: OUTPUT_JSON, dryRun, noSummary: noSummaryFlag } =
    parsePartnerArgs(argv)
  const noSummary = options.noSummary ?? noSummaryFlag

  assertPartnerExportTargets(exportPaths)

  if (!assertPsqlAvailable()) {
    throw new Error('Partner export requires psql on PATH')
  }

  setExportAsOfDate(new Date().toISOString().slice(0, 10))

  process.stderr.write(`Exporting partner counts from PostgreSQL (${formatDatabaseUrlForLog()})…\n`)
  const byNetwork = exportCountsFromDatabase()
  let countries = mergeCountryCounts(byNetwork)
  countries = rollupPartnerCountries(countries, NETWORK_KEYS)

  for (const [code, info] of Object.entries(COUNTRY_META_OVERRIDES)) {
    if (normalizePartnerIso(code) && !countries.has(code)) {
      countries.set(code, Object.fromEntries(NETWORK_KEYS.map((k) => [k, 0])))
    }
  }

  const meta = readExistingMetadata(OUTPUT)
  for (const [code, info] of Object.entries(COUNTRY_META_OVERRIDES)) {
    if (normalizePartnerIso(code)) {
      meta[code] = { ...meta[code], ...info }
    }
  }
  for (const dropped of ['HK', 'EN', 'AQ', 'UN', 'U-']) {
    delete meta[dropped]
  }

  const contributingCountries = countContributingCountries(countries)
  const output = renderPartnerCountries(countries, meta, contributingCountries)
  const outputJson = renderPartnerCountriesJson(countries, meta, contributingCountries)

  if (dryRun) {
    process.stdout.write(output)
    process.stdout.write(`\n\n--- partnerCountries.json preview ---\n`)
    process.stdout.write(`${JSON.stringify(outputJson, null, 2)}\n`)
    if (!noSummary) {
      printExportCriteriaSummary(byNetwork, { EXPORT_EDITION_LABEL })
    }
    return { byNetwork, countries, meta, contributingCountries }
  }

  const contributingIsos = listContributingCountryIsos(countries)

  fs.mkdirSync(path.dirname(OUTPUT), { recursive: true })
  fs.writeFileSync(OUTPUT, output, 'utf8')
  process.stderr.write(
    `Wrote ${OUTPUT} (${countries.size} ISO rows, ${contributingCountries} contributing countries)\n`,
  )

  fs.mkdirSync(path.dirname(OUTPUT_JSON), { recursive: true })
  fs.writeFileSync(OUTPUT_JSON, `${JSON.stringify(outputJson, null, 2)}\n`, 'utf8')
  process.stderr.write(`Wrote ${OUTPUT_JSON} (contributingCountries: ${contributingCountries})\n`)

  if (fs.existsSync(exportPaths.REPORT_CARD_ROOT)) {
    writeContributingCountriesYoy(exportPaths.REPORT_CARD_ROOT, contributingIsos)
  }

  if (!noSummary) {
    printExportCriteriaSummary(byNetwork, { EXPORT_EDITION_LABEL })
  }

  return { byNetwork, countries, contributingCountries }
}

/**
 * @param {string} reportCardRoot
 * @param {string[]} currentIsos
 */
function writeContributingCountriesYoy(reportCardRoot, currentIsos) {
  const editionDir = path.join(reportCardRoot, 'public/edition')
  const baselinePath = path.join(editionDir, 'contributing-countries-baseline.json')
  const snapshotPath = path.join(editionDir, 'contributing-countries-snapshot.json')
  const yoyPath = path.join(editionDir, 'contributing-countries-yoy.json')

  /** @type {string[]} */
  let previousIsos = []
  let previousYear = '2025'
  let previousSource = 'none'

  if (fs.existsSync(baselinePath)) {
    const baseline = JSON.parse(fs.readFileSync(baselinePath, 'utf8'))
    previousIsos = baseline.isos ?? []
    previousYear = String(baseline.year ?? previousYear)
    previousSource = 'baseline'
  } else if (fs.existsSync(snapshotPath)) {
    const snapshot = JSON.parse(fs.readFileSync(snapshotPath, 'utf8'))
    previousIsos = snapshot.isos ?? []
    previousYear = String(snapshot.year ?? previousYear)
    previousSource = 'snapshot'
  }

  const prevSet = new Set(previousIsos)
  const currSet = new Set(currentIsos)
  const appeared = currentIsos.filter((iso) => !prevSet.has(iso))
  const disappeared = previousIsos.filter((iso) => !currSet.has(iso))

  const baselineMissing = previousIsos.length === 0

  const payload = {
    exportedAt: new Date().toISOString().slice(0, 10),
    previousYear,
    previousSource,
    baselineMissing,
    currentCount: currentIsos.length,
    previousCount: previousIsos.length,
    delta: currentIsos.length - previousIsos.length,
    appeared: baselineMissing
      ? []
      : appeared.map((iso) => ({
          iso,
          name: ISO_COUNTRY_NAMES[iso] ?? iso,
        })),
    disappeared: baselineMissing
      ? []
      : disappeared.map((iso) => ({
          iso,
          name: ISO_COUNTRY_NAMES[iso] ?? iso,
        })),
  }

  fs.mkdirSync(editionDir, { recursive: true })
  fs.writeFileSync(yoyPath, `${JSON.stringify(payload, null, 2)}\n`, 'utf8')
  fs.writeFileSync(
    snapshotPath,
    `${JSON.stringify(
      {
        exportedAt: payload.exportedAt,
        year: new Date().getFullYear(),
        isos: currentIsos,
      },
      null,
      2,
    )}\n`,
    'utf8',
  )
  process.stderr.write(
    `  → ${path.relative(reportCardRoot, yoyPath)} (+${appeared.length} / −${disappeared.length})\n`,
  )
}

async function main() {
  await runPartnerExport()
}

function isDirectRun() {
  const entry = process.argv[1]
  if (!entry) return false
  return path.resolve(entry) === path.resolve(__filename)
}

if (isDirectRun()) {
  main().catch((err) => {
    console.error(err instanceof Error ? err.message : err)
    process.exit(1)
  })
}
