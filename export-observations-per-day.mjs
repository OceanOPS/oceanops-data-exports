#!/usr/bin/env node
/**
 * Export average daily observations for report card stat4.
 * Read-only step queries — source hierarchy, COUNT(*) per table, sum in Node.
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { formatDatabaseUrlForLog, runPsqlQuery } from './geojson-export/db.mjs'
import { loadDotEnv } from './databaseUrl.mjs'
import { buildExportMetadata } from './editionMetadata.mjs'
import { loadEditionValues } from './editionValues.mjs'
import { resolveExportPaths } from './paths.mjs'
import {
  OBS_FILTER_LABELS,
  OBS_FILTER_VARIANTS,
  aggregateDailyCounts,
  buildObservationSteps,
  mergeDailyCountLines,
  resolveObsFilter,
  resolveObsYear,
  resolveObservationRange,
} from './observations-export/queries.mjs'
import {
  HIERARCHY_NETWORKS,
  buildHierarchyNetworkYoySteps,
  computeDelta,
  summarizeDailyCounts,
} from './observations-export/hierarchyNetworkQueries.mjs'

/**
 * @param {{ avgObsPerDay: number, daysWindow: number, daysWithData: number, totalObs: number, exportedAt: string, obsFilter?: string, avgObsPerDayLastYear?: number, deltaVsLastYear?: number, yoyPreviousPeriod?: string, periodStart?: string, periodEnd?: string }} stats
 */
function renderEditionStatsTs(stats) {
  const filterNote =
    stats.obsFilter && stats.obsFilter !== 'hierarchy'
      ? `\n * obs filter: ${stats.obsFilter}`
      : ''
  const yoyLines =
    stats.avgObsPerDayLastYear !== undefined && stats.deltaVsLastYear !== undefined
      ? `
/** Same methodology, previous-year aligned window (for stat4 YoY badge). */
export const OBSERVATIONS_PER_DAY_AVG_LAST_YEAR = ${stats.avgObsPerDayLastYear}

/** Delta vs previous year (obs/day). */
export const OBSERVATIONS_PER_DAY_DELTA_VS_LAST_YEAR = ${stats.deltaVsLastYear}
`
      : ''
  return `/**
 * Edition headline stats — AUTO-GENERATED by oceanops-data-exports/export-observations-per-day.mjs
 * Regenerate: npm run export:observations (from oceanops-data-exports or oceanops-report-card)
 *
 * Source: observations-export/queries.mjs (source hierarchy, rolling average)${filterNote}
 * Last updated: ${stats.exportedAt}
 */

/** Rolling average of ocean observations per day (source hierarchy). */
export const OBSERVATIONS_PER_DAY_AVG = ${stats.avgObsPerDay}

/** Rolling window in days (edition.values.json → OBS_DAYS_WINDOW). */
export const OBSERVATIONS_DAYS_WINDOW = ${stats.daysWindow}

/** Days with at least one observation in the window. */
export const OBSERVATIONS_DAYS_WITH_DATA = ${stats.daysWithData}

/** Total observations in the window. */
export const OBSERVATIONS_TOTAL = ${stats.totalObs}

/** Inclusive start of the averaging window (ISO date). */
export const OBSERVATIONS_PERIOD_START = '${stats.periodStart ?? ''}'

/** Inclusive end of the averaging window (ISO date). */
export const OBSERVATIONS_PERIOD_END = '${stats.periodEnd ?? ''}'${yoyLines}
`
}

/** @param {string} metadataPath @param {Record<string, unknown>} patch */
function patchExportMetadata(metadataPath, patch) {
  /** @type {Record<string, unknown>} */
  let metadata = buildExportMetadata()
  if (fs.existsSync(metadataPath)) {
    metadata = { ...metadata, ...JSON.parse(fs.readFileSync(metadataPath, 'utf8')) }
  }
  fs.mkdirSync(path.dirname(metadataPath), { recursive: true })
  fs.writeFileSync(
    metadataPath,
    `${JSON.stringify({ ...metadata, ...patch }, null, 2)}\n`,
    'utf8',
  )
}

/**
 * @param {{ daysWindow?: number, year?: number | null, obsFilter: import('./observations-export/queries.mjs').ObsFilter, endDate?: Date }} range
 * @param {{ quiet?: boolean }} [opts]
 */
function collectObservationStats(range, opts = {}) {
  const stepOpts = { obsFilter: range.obsFilter }
  if (range.endDate) stepOpts.endDate = range.endDate
  if (range.year) stepOpts.year = range.year
  else stepOpts.daysWindow = range.daysWindow ?? 365

  const steps = buildObservationSteps(stepOpts)
  /** @type {Map<string, number>} */
  const byDay = new Map()

  if (!opts.quiet) {
    process.stderr.write(
      `${steps.length} read-only steps — ${OBS_FILTER_LABELS[range.obsFilter]} (no DDL)\n\n`,
    )
  }

  for (let i = 0; i < steps.length; i += 1) {
    const step = steps[i]
    if (!opts.quiet) {
      process.stderr.write(`[${i + 1}/${steps.length}] → ${step.label}…\n`)
    }

    const t0 = Date.now()
    const result = runPsqlQuery(step.sql)
    if (!result.ok) {
      throw new Error(`${step.label} failed: ${result.error}`)
    }

    const { lines, added } = mergeDailyCountLines(byDay, result.stdout)
    if (!opts.quiet) {
      const elapsed = ((Date.now() - t0) / 1000).toFixed(1)
      process.stderr.write(
        `     ${lines} day rows, +${added.toLocaleString('en-US')} obs (${elapsed}s)\n`,
      )
    }
  }

  if (!opts.quiet) {
    process.stderr.write(
      `\nTotal (summed): ${[...byDay.values()].reduce((a, b) => a + b, 0).toLocaleString('en-US')}\n`,
    )
  }
  return aggregateDailyCounts(byDay)
}

/** @param {Array<{ deltaPct: number | null, deltaAvg: number, label: string, source: string }>} rows */
function printNetworkYoyTable(rows) {
  process.stderr.write('\n--- Hierarchy networks YoY (avg obs/day) ---\n')
  process.stderr.write(
    `${'Network'.padEnd(28)} ${'Source'.padEnd(11)} ${'Prev avg'.padStart(10)} ${'Curr avg'.padStart(10)} ${'Delta'.padStart(10)} ${'%'.padStart(8)}\n`,
  )
  process.stderr.write(`${'-'.repeat(81)}\n`)
  for (const row of rows) {
    const pct = row.deltaPct === null ? '  n/a' : `${row.deltaPct >= 0 ? '+' : ''}${row.deltaPct}%`
    process.stderr.write(
      `${row.label.padEnd(28)} ${row.source.padEnd(11)} ${String(row.previous.avgPerDay).padStart(10)} ${String(row.current.avgPerDay).padStart(10)} ${(row.deltaAvg >= 0 ? '+' : '') + String(row.deltaAvg).padStart(9)} ${pct.padStart(8)}\n`,
    )
  }
}

/**
 * @param {{ daysWindow?: number, year?: number | null, endDate?: Date }} range
 * @param {{ quiet?: boolean }} [opts]
 */
function collectHierarchyNetworkYoy(range, opts = {}) {
  const yoyRange = range.year
    ? { year: range.year }
    : { daysWindow: range.daysWindow ?? 365, endDate: range.endDate }
  const { steps, current, previous, currentYear, previousYear } =
    buildHierarchyNetworkYoySteps(yoyRange)

  if (!opts.quiet) {
    process.stderr.write(
      `\nNetwork YoY: ${previous.label} vs ${current.label}\n${steps.length} read-only steps\n\n`,
    )
  }

  /** @type {Map<string, { current: Map<string, number>, previous: Map<string, number> }>} */
  const byNetwork = new Map()
  for (const network of HIERARCHY_NETWORKS) {
    byNetwork.set(network.id, { current: new Map(), previous: new Map() })
  }

  for (let i = 0; i < steps.length; i += 1) {
    const step = steps[i]
    if (!opts.quiet) {
      process.stderr.write(`[${i + 1}/${steps.length}] → ${step.label}…\n`)
    }

    const t0 = Date.now()
    const result = runPsqlQuery(step.sql)
    if (!result.ok) {
      throw new Error(`${step.label} failed: ${result.error}`)
    }

    const bucket = byNetwork.get(step.networkId)
    if (!bucket) throw new Error(`Unknown network id: ${step.networkId}`)

    const target = step.period === 'current' ? bucket.current : bucket.previous
    const { lines, added } = mergeDailyCountLines(target, result.stdout)
    if (!opts.quiet) {
      const elapsed = ((Date.now() - t0) / 1000).toFixed(1)
      process.stderr.write(
        `     ${lines} day rows, +${added.toLocaleString('en-US')} obs (${elapsed}s)\n`,
      )
    }
  }

  /** @type {Array<Record<string, unknown>>} */
  const networks = []
  for (const network of HIERARCHY_NETWORKS) {
    const bucket = byNetwork.get(network.id)
    if (!bucket) continue
    const currentStats = summarizeDailyCounts(bucket.current)
    const previousStats = summarizeDailyCounts(bucket.previous)
    const { deltaAvg, deltaPct } = computeDelta(currentStats, previousStats)
    networks.push({
      id: network.id,
      label: network.label,
      source: network.source,
      current: currentStats,
      previous: previousStats,
      deltaAvg,
      deltaPct,
    })
  }

  networks.sort((a, b) => {
    const ap = a.deltaPct ?? -Infinity
    const bp = b.deltaPct ?? -Infinity
    return ap - bp
  })

  if (!opts.quiet) {
    printNetworkYoyTable(networks)
  }

  return {
    currentYear,
    previousYear,
    currentPeriod: current.label,
    previousPeriod: previous.label,
    networks,
  }
}

/**
 * @param {{ daysWindow?: number, year?: number | null }} range
 * @param {import('./observations-export/queries.mjs').ObsFilter[]} filters
 */
function compareObsFilters(range, filters) {
  /** @type {Array<{ obsFilter: string, avgObsPerDay: number, daysWithData: number, totalObs: number, elapsedSec: string }>} */
  const rows = []
  const { rangeLabel } = resolveObservationRange(
    range.year ? { year: range.year } : { daysWindow: range.daysWindow ?? 365 },
  )

  process.stderr.write(
    `\nCompare obs filters (${rangeLabel})\nDB: ${formatDatabaseUrlForLog()}\n\n`,
  )

  for (const obsFilter of filters) {
    process.stderr.write(`=== ${obsFilter}: ${OBS_FILTER_LABELS[obsFilter]} ===\n`)
    const started = Date.now()
    const stats = collectObservationStats({ ...range, obsFilter }, { quiet: false })
    const elapsedSec = ((Date.now() - started) / 1000).toFixed(1)
    rows.push({ obsFilter, ...stats, elapsedSec })
    process.stderr.write(
      `→ avg ${stats.avgObsPerDay.toLocaleString('en-US')}/day, total ${stats.totalObs.toLocaleString('en-US')} (${elapsedSec}s)\n\n`,
    )
  }

  process.stderr.write('--- Summary ---\n')
  for (const row of rows) {
    process.stderr.write(
      `${row.obsFilter.padEnd(12)} avg ${String(row.avgObsPerDay).padStart(8)} /day  total ${String(row.totalObs).padStart(12)}  (${row.elapsedSec}s)\n`,
    )
  }

  return rows
}

/**
 * @param {string[]} [argv]
 * @param {{ noWrite?: boolean }} [opts]
 */
export async function runObservationsExport(argv = [], opts = {}) {
  loadDotEnv()
  const dryRun = argv.includes('--dry-run')
  const compare = argv.includes('--compare-obs-filters')
  const skipNetworkYoy = argv.includes('--skip-network-yoy')
  const obsFilter = resolveObsFilter(argv)
  const year = resolveObsYear(argv)
  const values = loadEditionValues()
  const daysWindow = Number.parseInt(String(values.OBS_DAYS_WINDOW ?? '365'), 10)
  const range = year ? { year } : { daysWindow }
  const exportedAt = new Date().toISOString().slice(0, 10)
  const paths = resolveExportPaths(argv)
  const editionStatsPath = path.join(paths.REPORT_CARD_ROOT, 'src/data/editionStats.ts')
  const reportMetadataPath = path.join(
    paths.REPORT_CARD_ROOT,
    'public/edition/export-metadata.json',
  )
  const mapMetadataPath = path.join(
    paths.SIMPLE_MAP_ROOT,
    'public/geojson/export-metadata.json',
  )
  const networkYoyPath = path.join(
    paths.REPORT_CARD_ROOT,
    'public/edition/observations-network-yoy.json',
  )

  if (dryRun) {
    if (compare) {
      for (const filter of OBS_FILTER_VARIANTS) {
        const steps = buildObservationSteps({ ...range, obsFilter: filter })
        process.stderr.write(`[dry-run] ${filter}: ${steps.length} read-only steps\n`)
      }
      return {
        avgObsPerDay: 0,
        daysWindow: year ? 365 : daysWindow,
        daysWithData: 0,
        totalObs: 0,
        exportedAt,
        year,
      }
    }
    const steps = buildObservationSteps({ ...range, obsFilter })
    process.stderr.write(
      `[dry-run] Would run ${steps.length} read-only steps (--obs-filter ${obsFilter}${year ? `, --year ${year}` : ''})\n`,
    )
    return {
      avgObsPerDay: 0,
      daysWindow: year ? 365 : daysWindow,
      daysWithData: 0,
      totalObs: 0,
      exportedAt,
      year,
    }
  }

  if (compare) {
    compareObsFilters(range, [...OBS_FILTER_VARIANTS])
    return {
      avgObsPerDay: 0,
      daysWindow: year ? 365 : daysWindow,
      daysWithData: 0,
      totalObs: 0,
      exportedAt,
      year,
    }
  }

  const resolvedRange = resolveObservationRange(range)
  const { rangeLabel, periodStart, periodEnd } = resolvedRange
  process.stderr.write(
    `\nObservations export (${rangeLabel}, obs-filter=${obsFilter})\nDB: ${formatDatabaseUrlForLog()}\n`,
  )

  const started = Date.now()
  const { avgObsPerDay, daysWithData, totalObs } = collectObservationStats({ ...range, obsFilter })

  /** YoY headline: same window shifted one year back (rolling) or calendar YTD (--year). */
  let avgObsPerDayLastYear
  let deltaVsLastYear
  let yoyPreviousPeriod
  if (!skipNetworkYoy) {
    process.stderr.write('\nPrevious-year window (headline YoY)…\n')
    if (year) {
      const prevStats = collectObservationStats(
        { year: year - 1, obsFilter },
        { quiet: true },
      )
      avgObsPerDayLastYear = prevStats.avgObsPerDay
      yoyPreviousPeriod = `calendar year ${year - 1}`
    } else {
      const previousEnd = new Date()
      previousEnd.setFullYear(previousEnd.getFullYear() - 1)
      const prevStats = collectObservationStats(
        { daysWindow, obsFilter, endDate: previousEnd },
        { quiet: true },
      )
      const { rangeLabel } = resolveObservationRange({ daysWindow, endDate: previousEnd })
      avgObsPerDayLastYear = prevStats.avgObsPerDay
      yoyPreviousPeriod = rangeLabel
    }
    deltaVsLastYear = avgObsPerDay - avgObsPerDayLastYear
    process.stderr.write(
      `  Previous avg: ${avgObsPerDayLastYear.toLocaleString('en-US')}/day → delta ${deltaVsLastYear >= 0 ? '+' : ''}${deltaVsLastYear.toLocaleString('en-US')}\n`,
    )
  }

  const elapsed = ((Date.now() - started) / 1000).toFixed(1)
  process.stderr.write(`\nFinished in ${elapsed}s — avg ${avgObsPerDay.toLocaleString('en-US')}/day\n`)

  const stats = {
    avgObsPerDay,
    daysWindow,
    daysWithData,
    totalObs,
    exportedAt,
    obsFilter,
    periodStart,
    periodEnd,
    ...(avgObsPerDayLastYear !== undefined && {
      avgObsPerDayLastYear,
      deltaVsLastYear,
      yoyPreviousPeriod,
    }),
  }

  if (!opts.noWrite && !skipNetworkYoy) {
    const networkYoy = collectHierarchyNetworkYoy(range)
    const networkPayload = {
      exportedAt,
      methodology: 'source hierarchy (GTS MF obs subsets + GDAC/IOOS/VOTO + AniBOS + FVON + tsunami OSMC)',
      currentYear: networkYoy.currentYear,
      previousYear: networkYoy.previousYear,
      currentPeriod: networkYoy.currentPeriod,
      previousPeriod: networkYoy.previousPeriod,
      headline: {
        currentAvgPerDay: avgObsPerDay,
        previousAvgPerDay: avgObsPerDayLastYear,
        deltaAvg: deltaVsLastYear,
      },
      networks: networkYoy.networks,
    }

    if (fs.existsSync(paths.REPORT_CARD_ROOT)) {
      fs.mkdirSync(path.dirname(networkYoyPath), { recursive: true })
      fs.writeFileSync(networkYoyPath, `${JSON.stringify(networkPayload, null, 2)}\n`, 'utf8')
      process.stderr.write(
        `\nWrote ${path.relative(paths.REPORT_CARD_ROOT, networkYoyPath)}\n`,
      )
    }
  }

  if (!opts.noWrite) {
    fs.mkdirSync(path.dirname(editionStatsPath), { recursive: true })
    fs.writeFileSync(editionStatsPath, renderEditionStatsTs(stats), 'utf8')
    process.stderr.write(
      `\nWrote ${path.relative(paths.REPORT_CARD_ROOT, editionStatsPath)} (avg: ${avgObsPerDay})\n`,
    )

    const metadataPatch = {
      OBSERVATIONS_PER_DAY_AVG: avgObsPerDay,
      OBSERVATIONS_DAYS_WINDOW: daysWindow,
      OBSERVATIONS_DAYS_WITH_DATA: daysWithData,
      OBSERVATIONS_TOTAL: totalObs,
      OBS_FILTER: obsFilter,
      OBSERVATIONS_PERIOD_START: periodStart,
      OBSERVATIONS_PERIOD_END: periodEnd,
      ...(avgObsPerDayLastYear !== undefined && {
        OBSERVATIONS_PER_DAY_AVG_LAST_YEAR: avgObsPerDayLastYear,
        OBSERVATIONS_PER_DAY_DELTA_VS_LAST_YEAR: deltaVsLastYear,
      }),
    }

    if (fs.existsSync(paths.REPORT_CARD_ROOT)) {
      patchExportMetadata(reportMetadataPath, metadataPatch)
      process.stderr.write(
        `  → ${path.relative(paths.REPORT_CARD_ROOT, reportMetadataPath)}\n`,
      )
    }

    if (fs.existsSync(paths.SIMPLE_MAP_ROOT) && fs.existsSync(path.dirname(mapMetadataPath))) {
      patchExportMetadata(mapMetadataPath, metadataPatch)
      process.stderr.write(`  → ${path.relative(paths.SIMPLE_MAP_ROOT, mapMetadataPath)}\n`)
    }
  }

  return stats
}

async function main() {
  try {
    await runObservationsExport(process.argv.slice(2))
  } catch (err) {
    console.error(err instanceof Error ? err.message : err)
    process.exit(1)
  }
}

function isDirectRun() {
  const entry = process.argv[1]
  if (!entry) return false
  return path.resolve(entry) === path.resolve(fileURLToPath(import.meta.url))
}

if (isDirectRun()) {
  void main()
}
